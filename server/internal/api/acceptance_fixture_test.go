// finding is one difference between the source's expected results and what
// the migrated application holds. The set of them is the machine-readable
// comparison #112 asks the fixture to produce.
type finding struct {
	Gate     string `json:"gate"`
	File     string `json:"file"`
	Path     string `json:"path"`
	Expected string `json:"expected"`
	Actual   string `json:"actual"`
}

type comparison struct {
	findings []finding
}

func (c *comparison) eq(gate, file, path string, expected, actual interface{}) bool {
	e, a := canonValue(expected), canonValue(actual)
	if e == a {
		return true
	}
	c.findings = append(c.findings, finding{Gate: gate, File: file, Path: path, Expected: e, Actual: a})
	return false
}

// eqValue compares a record value, honouring the manifest's marker for a cell
// whose empty-versus-null behaviour only the source run can settle.
func (c *comparison) eqValue(gate, file, path, marker string, expected string, actual interface{}) {
	if expected == marker {
		if canonValue(actual) == "" {
			return
		}
		c.findings = append(c.findings, finding{
			Gate: gate, File: file, Path: path,
			Expected: "empty or null", Actual: canonValue(actual),
		})
		return
	}
	c.eq(gate, file, path, expected, actual)
}

func (c *comparison) missing(gate, file, path, expected string) {
	c.findings = append(c.findings, finding{Gate: gate, File: file, Path: path, Expected: expected, Actual: "(absent)"})
}

// canonValue renders a value the way the manifest writes one, so a number the
// API answers as an exact decimal string and one it answers as a JSON number
// compare the same and neither is rounded on the way.
func canonValue(v interface{}) string {
	switch t := v.(type) {
	case nil:
		return ""
	case string:
		return t
	case bool:
		return strconv.FormatBool(t)
	case float64:
		return strconv.FormatFloat(t, 'f', -1, 64)
	case json.Number:
		return t.String()
	case int:
		return strconv.Itoa(t)
	default:
		return fmt.Sprintf("%v", t)
	}
}

func loadFixtureManifest(t *testing.T) *fixtureManifest {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(acceptanceFixtureDir, "expected.json"))
	require.NoError(t, err, "the acceptance fixture's expected-results manifest must be readable")
	var man fixtureManifest
	require.NoError(t, json.Unmarshal(raw, &man))
	require.NotEmpty(t, man.Files, "the fixture declares at least one source file")
	return &man
}

func fixtureText(t *testing.T, name string) string {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(acceptanceFixtureDir, name))
	require.NoError(t, err)
	return string(raw)
}

// TestAcceptanceFixture_AuthenticInputGate is the authentic-input gate of
// #112, and it is the one gate a repository cannot satisfy by itself: the
// inputs and the expected results have to come out of a real FileMaker
// installation. It skips with the exact procedure rather than passing on a
// handwritten fixture, so the gate's state is recorded on every run instead
// of being argued about.
func TestAcceptanceFixture_AuthenticInputGate(t *testing.T) {
	man := loadFixtureManifest(t)
	if man.Provenance != "filemaker" {
		t.Skipf(`acceptance gate "authentic input" is NOT met: fixture %q declares provenance %q.
To meet it, replace the design documents, the record exports and expected.json in %s with artefacts
generated by FileMaker Pro %s (%s), recorded as docs/LEGAL.md requires, and set "provenance": "filemaker".
The expected results must be what the SOURCE produced -- final data, calculation results, script
results and errors, container hashes -- not what File4Base produces.`,
			man.Fixture, man.Provenance, acceptanceFixtureDir, man.Source.Version, man.Source.Locale)
	}
}

// TestAcceptanceFixture_WorkflowExecutionGate records that the workflow gate
// cannot be met from here: the migrated script steps are executed by the
// Flutter client's runner and debugger, so a Go harness can compare their
// identity and order but can never run them.
func TestAcceptanceFixture_WorkflowExecutionGate(t *testing.T) {
	man := loadFixtureManifest(t)
	t.Skipf(`acceptance gate "workflow behavior" is NOT met by this harness: %s
Running the migrated workflow through its entry points belongs to the client suite
(client/test, LayoutActionRunner and ScriptDebugSession); this harness compares the
migrated steps' identity, order, operands and enabled state instead.`, man.Gates["workflow_behavior"])
}

// TestAcceptanceFixture_ImportAndCompare is the fixture itself: import the
// whole application and compare the result against the source's manifest.
func TestAcceptanceFixture_ImportAndCompare(t *testing.T) {
	man := loadFixtureManifest(t)
	h := newAPIHarness(t, api.Options{AllowPublicDatabaseCreation: true})
	cmp := &comparison{}

	type imported struct {
		database string
		token    string
	}
	byFile := map[string]imported{}

	for _, f := range man.Files {
		f := f
		t.Run("import "+f.Name, func(t *testing.T) {
			db := uniqueDB("f4b_acc")
			h.createDatabase(db, "owner", "owner-secret-9")
			token := h.login(db, "owner", "owner-secret-9")
			byFile[f.Name] = imported{database: db, token: token}

			request := map[string]interface{}{"design_xml": fixtureText(t, f.Design)}
			if len(f.Data) > 0 {
				data := map[string]string{}
				for table, file := range f.Data {
					data[table] = fixtureText(t, file)
				}
				request["data_files"] = data
			}

			// Gate: a preflight is read-only. It is run first, and the
			// solution must still be empty afterwards.
			var preflight struct {
				Status string                      `json:"status"`
				Report *migration.ConversionReport `json:"report"`
			}
			rec := h.do(http.MethodPost, "/api/v1/solutions/migrate/preflight", token, request, &preflight)
			require.Equal(t, http.StatusOK, rec.Code, rec.Body.String())
			cmp.eq("reliable_result", f.Name, "preflight.solution_name", f.SolutionName, preflight.Report.SolutionName)
			cmp.eq("reliable_result", f.Name, "preflight.tables_created", 0, len(h.observeTables(token)))

			// Apply into the same fresh database: the documented
			// file-to-solution binding, and nothing else.
			var applied struct {
				Status          string                      `json:"status"`
				RecordsInserted int                         `json:"records_inserted"`
				Report          *migration.ConversionReport `json:"report"`
			}
			rec = h.do(http.MethodPost, "/api/v1/solutions/migrate/apply", token, request, &applied)
			require.Equal(t, http.StatusCreated, rec.Code, rec.Body.String())

			cmp.eq("access_and_activation", f.Name, "report.triggers_quarantined",
				f.TriggersQuarantined, applied.Report.TriggersQuarantined)

			compareDefinitionIdentity(t, h, cmp, f, token)
			compareFieldBehavior(cmp, f, h.observeTables(token))
			compareAccessAndActivation(h, cmp, f, token)
			compareDataFidelity(h, cmp, man, f, token)
		})
	}

	if len(byFile) == len(man.Files) {
		t.Run("transfer the workflow returns by key", func(t *testing.T) {
			src, okSrc := byFile[man.Transfer.Source.File]
			dst, okDst := byFile[man.Transfer.Destination.File]
			require.True(t, okSrc && okDst, "both source files were imported")
			compareTransferBehavior(t, h, cmp, man, src.token, dst.token, dst.database)
		})
	}

	reportFindings(t, man, cmp)
}

// compareDefinitionIdentity checks the object graph: tables and fields by
// their source identity, occurrences including aliases and self-joins, join
// edges with their operator and side options, value lists, layout bindings,
// scripts with their operands, and external file references.
func compareDefinitionIdentity(t *testing.T, h *apiHarness, cmp *comparison, f fixtureFile, token string) {
	t.Helper()
	const gate = "definition_identity"

	tables := h.observeTables(token)
	tableByTarget := map[string]schema.TableMetadata{}
	tableByID := map[string]schema.TableMetadata{}
	for _, tbl := range tables {
		tableByTarget[tbl.Name] = tbl
		tableByID[tbl.ID] = tbl
	}
	cmp.eq(gate, f.Name, "tables.count", len(f.Tables), len(tables))

	for _, want := range f.Tables {
		got, ok := tableByTarget[want.Target]
		if !ok {
			cmp.missing(gate, f.Name, "table."+want.Target, want.Source)
			continue
		}
		cmp.eq(gate, f.Name, "table."+want.Target+".display_name", want.Source, got.DisplayName)

		colByTarget := map[string]schema.ColumnMetadata{}
		for _, col := range got.Columns {
			colByTarget[col.Name] = col
		}
		for _, wantCol := range want.Columns {
			path := "table." + want.Target + ".column." + wantCol.Target
			gotCol, ok := colByTarget[wantCol.Target]
			if !ok {
				cmp.missing(gate, f.Name, path, wantCol.Source+" as "+wantCol.Type)
				continue
			}
			cmp.eq(gate, f.Name, path+".display_name", wantCol.Source, gotCol.DisplayName)
			cmp.eq("field_behavior", f.Name, path+".type", wantCol.Type, string(gotCol.FieldType))
			cmp.eq("field_behavior", f.Name, path+".nullable", wantCol.Nullable, gotCol.IsNullable)
		}
	}

	// Occurrences, aliases and self-joins are objects of their own: an alias
	// that was folded into its base table would pass a count check.
	occurrences := h.observeOccurrences(token)
	occByID := map[string]schema.TableOccurrence{}
	occNames := make([]string, 0, len(occurrences))
	for _, occ := range occurrences {
		occByID[occ.ID] = occ
		occNames = append(occNames, occ.Name)
	}
	sort.Strings(occNames)
	wantOccs := append([]string(nil), f.Occurrences...)
	sort.Strings(wantOccs)
	cmp.eq(gate, f.Name, "occurrences", strings.Join(wantOccs, ","), strings.Join(occNames, ","))

	// A join edge, named as occurrence.column on each side, is the identity
	// the issue asks to be compared instead of a relationship count.
	edgeFor := func(occID, colID string) string {
		occ, ok := occByID[occID]
		if !ok {
			return "(unknown occurrence)"
		}
		tbl, ok := tableByID[occ.BaseTableID]
		if !ok {
			return occ.Name + ".(unknown table)"
		}
		for _, col := range tbl.Columns {
			if col.ID == colID {
				return occ.Name + "." + col.Name
			}
		}
		return occ.Name + ".(unknown column)"
	}
	relByName := map[string]schema.RelationshipMetadata{}
	for _, rel := range h.observeRelationships(token) {
		relByName[rel.Name] = rel
	}
	cmp.eq(gate, f.Name, "relationships.count", len(f.Relationships), len(relByName))
	for _, want := range f.Relationships {
		got, ok := relByName[want.Name]
		if !ok {
			cmp.missing(gate, f.Name, "relationship."+want.Name, want.Left+" "+want.Operator+" "+want.Right)
			continue
		}
		path := "relationship." + want.Name
		cmp.eq(gate, f.Name, path+".left", want.Left, edgeFor(got.LeftOccurrenceID, got.LeftColumnID))
		cmp.eq(gate, f.Name, path+".operator", want.Operator, got.Operator)
		cmp.eq(gate, f.Name, path+".right", want.Right, edgeFor(got.RightOccurrenceID, got.RightColumnID))
		cmp.eq(gate, f.Name, path+".allow_creation", want.AllowCreation, got.AllowCreation)
		cmp.eq(gate, f.Name, path+".cascade_delete", want.CascadeDelete, got.CascadeDelete)
	}

	valueListByName := map[string]schema.ValueList{}
	for _, vl := range h.observeValueLists(token) {
		valueListByName[vl.Name] = vl
	}
	for _, want := range f.ValueLists {
		got, ok := valueListByName[want.Name]
		if !ok {
			cmp.missing(gate, f.Name, "value_list."+want.Name, strings.Join(want.Values, "|"))
			continue
		}
		cmp.eq(gate, f.Name, "value_list."+want.Name+".kind", want.Kind, string(got.Kind))
		cmp.eq(gate, f.Name, "value_list."+want.Name+".values",
			strings.Join(want.Values, "|"), strings.Join(schema.SplitCustomValues(got.CustomValues), "|"))
	}

	layoutByName := map[string]schema.LayoutMetadata{}
	for _, l := range h.observeLayouts(token) {
		layoutByName[l.Name] = l
	}
	for _, want := range f.Layouts {
		got, ok := layoutByName[want.Name]
		if !ok {
			cmp.missing(gate, f.Name, "layout."+want.Name, "bound to "+want.Table)
			continue
		}
		bound := "(unresolved)"
		if occ, ok := occByID[got.TableOccurrenceID]; ok {
			if tbl, ok := tableByID[occ.BaseTableID]; ok {
				bound = tbl.Name
			}
		}
		cmp.eq(gate, f.Name, "layout."+want.Name+".table", want.Table, bound)
	}

	scriptByName := map[string]schema.ScriptMetadata{}
	for _, s := range h.observeScripts(token) {
		scriptByName[s.Name] = s
	}
	for _, want := range f.Scripts {
		got, ok := scriptByName[want.Name]
		if !ok {
			cmp.missing(gate, f.Name, "script."+want.Name, fmt.Sprintf("%d steps", len(want.Steps)))
			continue
		}
		path := "script." + want.Name
		// A migrated script names its context as the source did; the
		// comparison is on the identity, not the spelling.
		cmp.eq(gate, f.Name, path+".context_table",
			strings.ToLower(want.ContextTable), strings.ToLower(got.ContextTable))
		cmp.eq(gate, f.Name, path+".steps.count", len(want.Steps), len(got.Steps))

		for i, wantStep := range want.Steps {
			if i >= len(got.Steps) {
				cmp.missing(gate, f.Name, fmt.Sprintf("%s.step[%d]", path, i+1), wantStep.Type)
				continue
			}
			gotStep := got.Steps[i]
			stepPath := fmt.Sprintf("%s.step[%d]", path, i+1)
			cmp.eq(gate, f.Name, stepPath+".type", wantStep.Type, gotStep.StepType)
			cmp.eq(gate, f.Name, stepPath+".enabled", wantStep.Enabled, gotStep.IsEnabled)
			if len(wantStep.Params) == 0 {
				continue
			}
			params := map[string]interface{}{}
			if len(gotStep.Params) > 0 {
				_ = json.Unmarshal(gotStep.Params, &params)
			}
			for key, wantValue := range wantStep.Params {
				cmp.eq(gate, f.Name, stepPath+".params."+key, wantValue, params[key])
			}
		}
	}

	refByName := map[string]schema.FileReference{}
	for _, ref := range h.observeFileReferences(token) {
		refByName[ref.Name] = ref
	}
	for _, want := range f.FileReferences {
		got, ok := refByName[want.Name]
		if !ok {
			cmp.missing(gate, f.Name, "file_reference."+want.Name, "declared")
			continue
		}
		// An unmapped reference is the correct state after an import: it must
		// never resolve to a same-named local script (#96, #107).
		cmp.eq("cross_file_behavior", f.Name, "file_reference."+want.Name+".mapped",
			want.Mapped, strings.TrimSpace(got.Database) != "")
	}
}

// compareFieldBehavior checks the field behaviour the fixture scope names: a
// calculation whose references follow the renamed fields, and the validation
// a source field carried.
func compareFieldBehavior(cmp *comparison, f fixtureFile, tables []schema.TableMetadata) {
	const gate = "field_behavior"
	colByPath := map[string]schema.ColumnMetadata{}
	for _, tbl := range tables {
		for _, col := range tbl.Columns {
			colByPath[tbl.Name+"."+col.Name] = col
		}
	}
	for _, tbl := range f.Tables {
		for _, want := range tbl.Columns {
			if want.Formula == "" {
				continue
			}
			path := "table." + tbl.Target + ".column." + want.Target + ".formula"
			got, ok := colByPath[tbl.Target+"."+want.Target]
			if !ok {
				cmp.missing(gate, f.Name, path, want.Formula)
				continue
			}
			if got.CalculationFormula == nil {
				cmp.missing(gate, f.Name, path, want.Formula)
				continue
			}
			var payload struct {
				Formula string `json:"formula"`
			}
			_ = json.Unmarshal([]byte(*got.CalculationFormula), &payload)
			cmp.eq(gate, f.Name, path, want.Formula, payload.Formula)
		}
	}
}

// compareAccessAndActivation checks that nothing the import brought in is
// live: an imported account must arrive without access, and an imported
// script and its triggers must arrive inactive.
func compareAccessAndActivation(h *apiHarness, cmp *comparison, f fixtureFile, token string) {
	const gate = "access_and_activation"
	userByName := map[string]schema.UserMetadata{}
	for _, u := range h.observeUsers(token) {
		userByName[strings.ToLower(u.Username)] = u
	}
	for _, want := range f.Accounts {
		got, ok := userByName[strings.ToLower(want.Name)]
		if !ok {
			cmp.missing(gate, f.Name, "account."+want.Name, "imported")
			continue
		}
		cmp.eq(gate, f.Name, "account."+want.Name+".active", want.Active, got.IsActive)
	}
	scriptByName := map[string]schema.ScriptMetadata{}
	for _, s := range h.observeScripts(token) {
		scriptByName[s.Name] = s
	}
	for _, want := range f.Scripts {
		if got, ok := scriptByName[want.Name]; ok {
			cmp.eq(gate, f.Name, "script."+want.Name+".active", want.Active, got.IsActive)
		}
	}
}

// compareDataFidelity accounts for every source record by its business key
// and compares the values exactly: decimals as written, Unicode intact and
// whitespace untrimmed.
func compareDataFidelity(h *apiHarness, cmp *comparison, man *fixtureManifest, f fixtureFile, token string) {
	const gate = "data_fidelity"
	for table, want := range f.Records {
		rows := h.observeRows(token, table)
		cmp.eq(gate, f.Name, "records."+table+".count", len(want.Rows), len(rows))

		byKey := map[string]map[string]interface{}{}
		for _, row := range rows {
			byKey[canonValue(row[want.Key])] = row
		}
		for _, wantRow := range want.Rows {
			key := wantRow[want.Key]
			got, ok := byKey[key]
			if !ok {
				cmp.missing(gate, f.Name, "records."+table+"["+key+"]", "present")
				continue
			}
			for field, wantValue := range wantRow {
				cmp.eqValue(gate, f.Name,
					"records."+table+"["+key+"]."+field, man.EmptyMarker, wantValue, got[field])
			}
		}
	}
}

// compareTransferBehavior runs the cross-file leg: send by stable key, replay
// it, and then inject a row the destination cannot accept and check that the
// refused run left the destination exactly as the replay left it.
func compareTransferBehavior(
	t *testing.T,
	h *apiHarness,
	cmp *comparison,
	man *fixtureManifest,
	sourceToken, destinationToken, destinationDB string,
) {
	t.Helper()
	const gate = "cross_file_behavior"
	spec := man.Transfer

	mappings := make([]map[string]string, 0, len(spec.Mappings))
	for _, m := range spec.Mappings {
		mappings = append(mappings, map[string]string{"source_field": m.Source, "destination_field": m.Destination})
	}
	definition := map[string]interface{}{
		"name":         spec.Name,
		"source":       map[string]string{"table": spec.Source.Table},
		"destination":  map[string]string{"database": destinationDB, "table": spec.Destination.Table},
		"mappings":     mappings,
		"match_fields": spec.MatchFields,
		"mode":         spec.Mode,
		"on_unmatched": spec.OnUnmatched,
		"on_rejected":  spec.OnRejected,
		"date_order":   "iso",
	}
	var created schema.TransferDefinition
	rec := h.do(http.MethodPost, "/api/v1/transfers", sourceToken, definition, &created)
	require.Equal(t, http.StatusCreated, rec.Code, rec.Body.String())

	run := func(id string) (*transfer.Report, int) {
		var res struct {
			*transfer.Report
			Error string `json:"error,omitempty"`
		}
		rec := h.do(http.MethodPost, "/api/v1/transfers/"+id+"/run", sourceToken,
			map[string]string{"peer_token": destinationToken}, &res)
		return res.Report, rec.Code
	}

	report, _ := run(created.ID)
	require.NotNil(t, report, "a run always answers a report")
	cmp.eq(gate, "transfer", "first_run.added", spec.FirstRun.Added, report.Added)
	cmp.eq(gate, "transfer", "first_run.updated", spec.FirstRun.Updated, report.Updated)
	cmp.eq(gate, "transfer", "first_run.rejected", spec.FirstRun.Rejected, report.RejectedCount())
	cmp.eq(gate, "transfer", "first_run.committed", spec.FirstRun.Committed, report.Committed)

	replay, _ := run(created.ID)
	require.NotNil(t, replay)
	cmp.eq(gate, "transfer", "replay.added", spec.Replay.Added, replay.Added)
	cmp.eq(gate, "transfer", "replay.updated", spec.Replay.Updated, replay.Updated)
	cmp.eq(gate, "transfer", "replay.rejected", spec.Replay.Rejected, replay.RejectedCount())
	cmp.eq(gate, "transfer", "replay.committed", spec.Replay.Committed, replay.Committed)

	// The destination after the replay: no duplicates, and the retained
	// fields unchanged.
	rows := h.observeRows(destinationToken, spec.Destination.Table)
	cmp.eq(gate, "transfer", "destination.count", len(spec.After.Rows), len(rows))
	byKey := map[string]map[string]interface{}{}
	for _, row := range rows {
		byKey[canonValue(row[spec.After.Key])] = row
	}
	for _, wantRow := range spec.After.Rows {
		key := wantRow[spec.After.Key]
		got, ok := byKey[key]
		if !ok {
			cmp.missing(gate, "transfer", "destination["+key+"]", "present")
			continue
		}
		for field, wantValue := range wantRow {
			cmp.eqValue(gate, "transfer", "destination["+key+"]."+field, man.EmptyMarker, wantValue, got[field])
		}
	}

	// A rejected row, and the refused run that must change nothing.
	probeMappings := make([]map[string]string, 0, len(spec.Probe.Mappings))
	for _, m := range spec.Probe.Mappings {
		probeMappings = append(probeMappings, map[string]string{"source_field": m.Source, "destination_field": m.Destination})
	}
	probe := map[string]interface{}{
		"name":         spec.Probe.Name,
		"source":       map[string]string{"table": spec.Source.Table},
		"destination":  map[string]string{"database": destinationDB, "table": spec.Destination.Table},
		"mappings":     probeMappings,
		"match_fields": spec.MatchFields,
		"mode":         spec.Mode,
		"on_unmatched": spec.OnUnmatched,
		"on_rejected":  spec.Probe.OnRejected,
		"date_order":   "iso",
	}
	var probeCreated schema.TransferDefinition
	rec = h.do(http.MethodPost, "/api/v1/transfers", sourceToken, probe, &probeCreated)
	require.Equal(t, http.StatusCreated, rec.Code, rec.Body.String())

	probeReport, _ := run(probeCreated.ID)
	require.NotNil(t, probeReport)
	cmp.eq(gate, "transfer", "rejection_probe.committed", spec.Probe.Expected.Committed, probeReport.Committed)
	if probeReport.RejectedCount() < spec.Probe.Expected.MinRejected {
		cmp.findings = append(cmp.findings, finding{
			Gate: gate, File: "transfer", Path: "rejection_probe.rejected",
			Expected: fmt.Sprintf("at least %d", spec.Probe.Expected.MinRejected),
			Actual:   strconv.Itoa(probeReport.RejectedCount()),
		})
	}
	after := h.observeRows(destinationToken, spec.Destination.Table)
	cmp.eq(gate, "transfer", "rejection_probe.destination_unchanged", len(spec.After.Rows), len(after))
}

// reportFindings writes the comparison out as the machine-readable artefact
// #112 asks for, and fails the test when the application did not migrate.
func reportFindings(t *testing.T, man *fixtureManifest, cmp *comparison) {
	t.Helper()
	path := filepath.Join(t.TempDir(), "acceptance_differences.json")
	payload := map[string]interface{}{
		"fixture":    man.Fixture,
		"provenance": man.Provenance,
		"source":     man.Source,
		"gates":      man.Gates,
		"findings":   cmp.findings,
	}
	encoded, err := json.MarshalIndent(payload, "", "  ")
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(path, encoded, 0o600))
	t.Logf("machine-readable comparison: %s", path)

	if len(cmp.findings) == 0 {
		return
	}
	for _, f := range cmp.findings {
		t.Errorf("[%s] %s %s: expected %q, got %q", f.Gate, f.File, f.Path, f.Expected, f.Actual)
	}
	t.Logf("%s", encoded)
}

