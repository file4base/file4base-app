// The application-level acceptance fixture of #112.
//
// This is not another unit test of the converter. It takes a whole two-file
// FileMaker application from `testdata/acceptance/<fixture>`, imports it
// through the documented HTTP path exactly as a person would, and compares
// what the target then holds against an expected-results manifest that was
// written from the source, not from File4Base. Every difference is collected
// as a machine-readable finding rather than failing on the first one, so one
// run says how far the application actually migrated.
//
// What it deliberately does NOT do:
//
//   - It does not build the destination application. Nothing here creates a
//     table, a field, a relationship, a script or an account: if the import
//     did not produce it, it is missing, and the finding says so.
//   - It does not claim the acceptance gate of #112 passes. The gate needs
//     inputs and an expected-results manifest generated by a real FileMaker
//     installation; this fixture's manifest declares its own provenance, and
//     TestAcceptanceFixture_AuthenticInputGate skips, loudly, until that
//     provenance is "filemaker".
//   - It does not run the migrated workflow. File4Base executes script steps
//     in the Flutter client, so the workflow gate cannot be met from a Go
//     test at all; the manifest records that, and the steps' identity and
//     order are compared here instead.

